WITH date_checks AS (
    SELECT 
        merchant_id,
        valid_from,
        valid_to,
        -- Fetch the next row's starting date
        LEAD(valid_from) OVER (
            PARTITION BY merchant_id 
            ORDER BY valid_from
        ) AS next_valid_from
    FROM dim_merchant_scd2
)
SELECT 
    merchant_id,
    valid_from,
    valid_to,
    next_valid_from,
    CASE 
        WHEN valid_to < next_valid_from THEN 'Gap'
        WHEN valid_to > next_valid_from THEN 'Overlap'
    END AS issue_type
FROM date_checks
-- Filter for rows where valid_to doesn't cleanly transition to the next valid_from
WHERE valid_to IS DISTINCT FROM next_valid_from
and (valid_to < next_valid_from or valid_to > next_valid_from);