
DROP TABLE IF EXISTS dim_merchant_scd2;


CREATE TABLE dim_merchant_scd2(merchant_sk integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY --surrogate key 1,2,3
 ,merchant_id text NOT NULL -- id from merchans
 ,name text -- name
 ,category text -- category
 ,country text NOT NULL -- country
 ,valid_from date NOT NULL --valid from date 
 ,valid_to date NOT NULL--valid to date    
 ,is_current boolean not null -- is this row a current/valid merchant by date
 ,CONSTRAINT uq_dim_merchant_scd2_merchant_id_valid_from UNIQUE (merchant_id, valid_from)
);

COMMENT ON COLUMN dim_merchant_scd2.name     IS 'SCD Type 1: overwritten, no history';
COMMENT ON COLUMN dim_merchant_scd2.category IS 'SCD Type 2: change of category creates a new version';
COMMENT ON COLUMN dim_merchant_scd2.country  IS 'SCD Type 2: change of country creates a new version';

insert into dim_merchant_scd2 
